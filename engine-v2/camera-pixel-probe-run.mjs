import assert from "node:assert/strict";
import { open, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { build } from "esbuild";
import { startChrome } from "../scripts/diagnostics/chrome-session.mjs";
import { serve } from "./serve.mjs";

const [chromePath, handFile, modelFile, camera, output] = process.argv.slice(2);
assert(output, "Supply Chrome, hand Landmarker, model, original 12 s lead-in Y4M fixture, and output");
const file = await open(camera);
let reference, width, height, fps;
const frameCount = 50, leadIn = 12;
try {
  const header = Buffer.alloc(160);
  await file.read(header, 0, header.length, 0);
  const headerEnd = header.indexOf(10);
  const parts = /^YUV4MPEG2 W(\d+) H(\d+) F(\d+):1 Ip A1:1 C420$/.exec(header.subarray(0, headerEnd).toString());
  assert(parts, "Expected uncompressed planar 4:2:0 generated by make_asl_camera_fixture.py");
  [, width, height, fps] = parts.map(Number);
  const stride = width * height * 1.5;
  assert(width % 2 === 0 && height % 2 === 0 && width * height <= 640 * 640 && fps > 0 && fps <= 60);
  reference = Buffer.alloc(stride * frameCount);
  const delimiter = Buffer.alloc(6);
  for (let i = 0; i < frameCount; i++) {
    const offset = headerEnd + 1 + (leadIn * fps + i) * (stride + 6);
    await file.read(delimiter, 0, 6, offset);
    assert.equal(delimiter.toString(), "FRAME\n");
    assert.equal((await file.read(reference, i * stride, stride, offset + 6)).bytesRead, stride);
  }
} finally {
  await file.close();
}
const script = await build({ entryPoints: ["engine-v2/camera-pixel-probe.mjs"], bundle: true,
  format: "iife", platform: "browser", write: false });
const server = await serve({ handFile, modelFile, port: 0, diagnostics: new Map([
  ["/probe", { data: "<!doctype html><title>Frame parity probe</title><script src='/probe.js'></script>", type: "text/html" }],
  ["/probe.js", { data: script.outputFiles[0].contents, type: "text/javascript" }],
  ["/reference.i420", { data: reference, type: "application/octet-stream" }],
]) });
let browser;
try {
  browser = await startChrome(chromePath, { proxy: "http://127.0.0.1:9",
    extraArgs: ["--use-file-for-fake-video-capture=" + resolve(camera)] });
  await browser.send("Page.navigate", { url: "http://127.0.0.1:" + server.address().port + "/probe" });
  for (let i = 0; i < 120 && !await browser.evaluate("typeof compareCameraPixels === 'function'"); i++) {
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  const result = await browser.evaluate(`compareCameraPixels(${JSON.stringify({ width, height, fps, leadIn, frameCount })})`);
  await writeFile(output, JSON.stringify(result, null, 2));
  console.log(JSON.stringify({ captured: result.captured, matched: result.matched.length, dimensions: result.dimensions,
    pixelError: Math.min(...result.matched.map(row => row.error)), source: [result.source.hands, result.source.label],
    camera: [result.camera.hands, result.camera.label] }));
} finally {
  await browser?.close();
  server.close();
}
