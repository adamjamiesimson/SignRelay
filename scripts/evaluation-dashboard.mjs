// Local evaluation dashboard from existing JSONL outputs. Aggregates only:
// it refuses rows carrying landmark/frame sequences and never claims
// accuracy for evidence that does not exist (absent negatives are "not measured").
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { summarizeTrials } from "./evaluation-metrics.mjs";
import { signerKey } from "./signer-identity.mjs";

const SEQUENCE_KEYS = /landmark|trace|timeline|keypoint|^pose$|^face$|^hands$|frame_data|coordinates/i;
const pct = (value, digits = 0) => value === null || value === undefined ? "—" : `${(value * 100).toFixed(digits)}%`;
const unique = values => [...new Set(values.filter(value => value !== undefined && value !== null))];

export function assertAggregateOnly(rows, label) {
  for (const [index, row] of rows.entries()) for (const [key, value] of Object.entries(row)) {
    if (SEQUENCE_KEYS.test(key) && (Array.isArray(value) || (value && typeof value === "object" && key !== "handedness_counts")))
      throw new Error(`${label} row ${index + 1}: '${key}' looks like a raw landmark/frame sequence; dashboards accept aggregates only`);
  }
}

/** @param {{label: string, file: string, rows: object[]}[]} sources @param {{currentWorker?: string | null}} [options] */
export function buildDashboard(sources, { currentWorker = null } = {}) {
  for (const source of sources) assertAggregateOnly(source.rows, source.label);
  const all = sources.flatMap(source => source.rows.map(row => ({ ...row, __source: source.label })));
  const hashes = all.map(row => row.recording_sha256).filter(Boolean);
  if (new Set(hashes).size !== hashes.length) throw new Error("The same recording appears in two sources; it would be double-counted");
  const [summary] = summarizeTrials(sources.flatMap(source => source.rows)).filter(group => group.group.startsWith("asl/"));
  const workers = unique(all.map(row => row.worker_sha256));
  const lines = [];
  lines.push("# ASL evaluation dashboard (development evidence only)", "");
  lines.push("> Generated by `scripts/evaluation-dashboard.mjs` from committed aggregate JSONL. These are **previously inspected, publisher-labelled development recordings**, not an unseen test set, independent fluent review, or real-world accuracy. The sealed holdout was not used.", "");
  lines.push("## Provenance", "", "| Source | File | Trials | Participants | Worker | Commit | Harness dirty |", "| --- | --- | ---: | ---: | --- | --- | --- |");
  for (const source of sources) {
    const rows = source.rows;
    lines.push(`| ${source.label} | \`${source.file}\` | ${rows.length} | ${new Set(rows.map(row => signerKey(row.participant_id))).size} | ${unique(rows.map(row => row.worker_sha256?.slice(0, 12))).join(", ") || "—"} | ${unique(rows.map(row => row.source_commit?.slice(0, 9))).join(", ") || "—"} | ${unique(rows.map(row => String(row.harness_dirty))).join(", ")} |`);
  }
  lines.push("");
  if (currentWorker) {
    const fresh = workers.length === 1 && workers[0] === currentWorker;
    lines.push(fresh
      ? `Current \`public/workers/recognition.worker.js\` (${currentWorker.slice(0, 12)}) is byte-identical to the evaluated worker, so these results describe the current recognizer.`
      : `**Stale:** the current worker (${currentWorker.slice(0, 12)}) differs from the evaluated worker(s) (${workers.map(w => w.slice(0, 12)).join(", ")}). Re-run the video pilot before quoting these numbers for this build.`, "");
  }
  lines.push("## Signed trials", "", `**${summary.correct} correct, ${summary.wrong_accepted_trials} wrong accepted, ${summary.abstentions} abstained, ${summary.signed_errors} errored, of ${summary.signed_trials} signed trials** from ${summary.unique_participants} publisher participant IDs.`, "");
  lines.push("| Sign | Trials | Correct | Wrong accepted | Abstained | Errored | Frames with a tracked hand |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: |");
  for (const row of summary.per_gloss) {
    const tracking = row.hand_tracking.frames ? `${row.hand_tracking.frames_with_hands}/${row.hand_tracking.frames} (${pct(row.hand_tracking.frames_with_hands / row.hand_tracking.frames)})` : "—";
    lines.push(`| ${row.gloss} | ${row.trials} | ${row.correct} | ${row.wrong_accepted} | ${row.abstentions} | ${row.errors} | ${tracking} |`);
  }
  lines.push("", `With n=${summary.signed_trials}, a single trial moves any rate by ${pct(1 / Math.max(summary.signed_trials, 1))}. No confidence interval supports a public accuracy claim.`, "");
  lines.push("## Per-trial outcomes", "", "| Source | Trial | Expected | Outcome | Hand frames | Candidate sources |", "| --- | --- | --- | --- | ---: | --- |");
  for (const row of all.filter(item => item.trial_type === "sign")) {
    const outcome = row.status && row.status !== "complete" ? "ERROR" : !row.accepted ? "abstained"
      : (row.accepted_glosses ?? [row.predicted_gloss]).every(gloss => gloss === row.expected_gloss) ? "correct" : `wrong: ${(row.accepted_glosses ?? []).join(", ")}`;
    const candidates = Object.entries(row.candidate_sources ?? {}).map(([key, count]) => `${key} ${count}`).join(", ") || "—";
    lines.push(`| ${row.__source} | ${row.trial_id} | ${row.expected_gloss} | ${outcome} | ${row.hand_frames ?? "—"}/${row.frames ?? "—"} | ${candidates} |`);
  }
  lines.push("", "## False acceptance on non-signing and unsupported signs", "");
  for (const [label, negatives] of [["No-sign activity", summary.no_sign], ["Unsupported (out-of-vocabulary) sign", summary.unknown_sign]]) {
    lines.push(negatives.trials
      ? `- ${label}: ${negatives.false_accepts} false accepts in ${negatives.trials} trials (${negatives.errors} errored; rate ${negatives.rate === null ? "withheld" : pct(negatives.rate)}).`
      : `- ${label}: **not measured** — 0 trials exist. This is absence of evidence, not zero false positives.`);
  }
  lines.push("", "## What this does not show", "", "- Accuracy on new signers, devices, lighting, phones, or live camera use.",
    "- Independent fluent ASL confirmation of the publisher labels.", "- False-acceptance rates for resting hands, conversation gestures or unsupported signs.",
    "- Any result for BSL, ISL, LSE, PSL, RSL or Bangla live use.", "");
  return { markdown: lines.join("\n"), summary };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  const outIndex = args.indexOf("--out");
  const out = outIndex >= 0 ? args.splice(outIndex, 2)[1] : null;
  if (!args.length) throw new Error("Usage: node scripts/evaluation-dashboard.mjs LABEL=FILE.jsonl [...] [--out FILE.md]");
  const sources = args.map(arg => {
    const [label, file] = arg.includes("=") ? arg.split("=") : [arg, arg];
    return { label, file, rows: readFileSync(file, "utf8").trim().split("\n").filter(Boolean).map(line => JSON.parse(line)) };
  });
  const worker = "public/workers/recognition.worker.js";
  const currentWorker = existsSync(worker) ? createHash("sha256").update(readFileSync(worker)).digest("hex") : null;
  const { markdown } = buildDashboard(sources, { currentWorker });
  if (out) writeFileSync(out, markdown + "\n");
  else console.log(markdown);
}
